// Run only against a disposable, uninitialized development API.
import { createRequire } from 'node:module'
import { readFileSync } from 'node:fs'
import assert from 'node:assert/strict'
const require = createRequire(new URL('../apps/web/package.json', import.meta.url))
const { chromium } = require('playwright')
const base = 'http://localhost:5173'
const env = Object.fromEntries(readFileSync(new URL('../.env', import.meta.url), 'utf8').split('\n').filter(l=>l.includes('=')).map(l=>{const i=l.indexOf('=');return [l.slice(0,i),l.slice(i+1)]}))
const browser = await chromium.launch({headless:true,args:['--no-sandbox']})
const errors=[]
try {
 const page=await browser.newPage({viewport:{width:390,height:844}})
 page.setDefaultTimeout(120000)
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto(base)
 await page.getByLabel('部署密钥',{exact:true}).fill(env.CONTROL_TOKEN)
 await page.screenshot({path:'/tmp/remote-setup.png'})
 await page.getByRole('button',{name:'下一步'}).click()
 await page.getByLabel('管理员账号',{exact:true}).fill('smoke-admin')
 await page.getByLabel('登录密码',{exact:true}).fill('smoke-password-1234')
 await page.getByLabel('确认密码',{exact:true}).fill('wrong-password-1234')
 await page.getByRole('button',{name:'下一步'}).click()
 await page.getByText('两次输入的密码不一致',{exact:true}).waitFor()
 await page.getByLabel('确认密码',{exact:true}).fill('smoke-password-1234')
 await page.getByRole('button',{name:'下一步'}).click()
 await page.getByLabel('工作空间名称').fill('Smoke workspace')
 await page.getByRole('button',{name:'下一步'}).click()
 await page.getByRole('button',{name:'完成初始化并进入系统'}).click()
 await page.waitForURL(base+'/')
 await page.goto(base+'/management')
 await page.getByLabel('工作空间名称').fill('Updated workspace')
 await page.getByRole('button',{name:'保存连接设置'}).click()
 await page.getByText('设置已保存，将用于新连接',{exact:true}).waitFor()
 await page.reload()
 assert.equal(await page.getByLabel('工作空间名称').inputValue(),'Updated workspace')
 await page.getByRole('tab',{name:'Token 管理'}).click()
 await page.getByLabel('名称',{exact:true}).fill('Smoke token')
 await page.getByRole('button',{name:'创建 Token',exact:true}).click()
 const secret=await page.getByRole('textbox',{name:'新 Token',exact:true}).inputValue()
 assert.ok(secret.startsWith('rc_host_'))
 await page.getByRole('button',{name:'已保存，关闭'}).click()
 const row=page.getByRole('row').filter({hasText:'Smoke token'})
 await row.getByRole('button',{name:'撤销',exact:true}).click()
 await page.getByRole('button',{name:'确认撤销',exact:true}).click()
 await row.getByText('已撤销',{exact:true}).waitFor()
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile management fits viewport')
 await page.screenshot({path:'/tmp/remote-management.png'})
 await page.getByRole('tab',{name:'账号安全'}).click()
 await page.getByLabel('当前密码',{exact:true}).fill('smoke-password-1234')
 await page.getByLabel('新密码',{exact:true}).fill('smoke-replacement-1234')
 await page.getByLabel('确认新密码',{exact:true}).fill('smoke-replacement-1234')
 await page.getByRole('button',{name:'修改密码并重新登录'}).click()
 await page.waitForURL(base+'/login')
 await page.getByLabel('账号',{exact:true}).fill('smoke-admin')
 await page.getByLabel('密码',{exact:true}).fill('smoke-replacement-1234')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await page.waitForURL(base+'/')
 await page.reload()
 await page.getByRole('button',{name:'退出登录'}).click()
 await page.waitForURL(base+'/login')
 await page.screenshot({path:'/tmp/remote-login.png'})
 assert.deepEqual(errors,[])
 console.log('PASS: mobile setup, validation, persistent login, settings, one-time token, revocation, password change and logout.')
} finally {await browser.close()}
